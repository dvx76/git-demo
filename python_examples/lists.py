"""Voorbeelden: werken met lists."""
# Een lijst met fruit aanmaken
fruit_lijst = ["appel", "banaan", "kers", "mango"]

# Het eerste item opvragen (Python begint altijd te tellen vanaf 0!)
print(fruit_lijst[0])  # Output: appel

# Het laatste item opvragen met een negatieve index
print(fruit_lijst[-1]) # Output: mango